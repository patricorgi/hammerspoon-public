local history = {}
local state = require("launcher-clipboard-state")
local snapshot = state.load()
local entries = snapshot and snapshot.entries or {}
local clearedChangeCount = snapshot and snapshot.clearedChangeCount
local observedChangeCount = snapshot and snapshot.observedChangeCount
local personalEntries
local maxEntries = 60
local maxImages = 12
local maxImageBytes = 16 * 1024 * 1024
local excludedTypes = {
    ["org.nspasteboard.ConcealedType"] = true,
    ["org.nspasteboard.TransientType"] = true,
    ["org.nspasteboard.AutoGeneratedType"] = true,
}

local function remove(index)
    local entry = table.remove(entries, index)
    if entry.previewImage then
        if personalEntries then os.remove(entry.previewImage) else state.removeImage(entry.previewImage) end
    end
end

local trackingParameters = { fbclid = true, gclid = true, dclid = true, msclkid = true }

local function cleanURL(text)
    local url = text:match("^%s*(.-)%s*$")
    if url:find("[%s%c]") then return end
    local base, query, fragment = url:match("^([Hh][Tt][Tt][Pp][Ss]?://[^?#]+)%?([^#]*)(.*)$")
    if not base then return end
    local kept, changed = {}, false
    for parameter in (query .. "&"):gmatch("(.-)&") do
        local key = (parameter:match("^[^=]*"):gsub("%%(%x%x)", function(hex)
            return string.char(tonumber(hex, 16))
        end)):lower()
        if key:find("signature", 1, true) or key == "sig" or key == "token" or key == "access_token" then
            return
        end
        if key:sub(1, 4) == "utm_" or trackingParameters[key] then
            changed = true
        else
            kept[#kept + 1] = parameter
        end
    end
    if changed then
        local suffix = #kept > 0 and ("?" .. table.concat(kept, "&")) or ""
        return base .. suffix .. fragment
    end
end

local function textEntry(text)
    for i, previous in ipairs(entries) do
        if previous.previewText == text then remove(i); break end
    end
    local title = text:gsub("%s+", " "):match("^%s*(.-)%s*$")
    local stop = utf8.offset(title, 121)
    if stop then title = title:sub(1, stop - 1) .. "…" end
    return { text = title, symbol = "doc.text", previewText = text }
end

local capturePaused = false

local function save()
    if personalEntries then return end
    if not state.save(entries, observedChangeCount, clearedChangeCount) then
        hs.printf("GlassLauncher could not save clipboard history")
    end
end

function history.setRecording(enabled)
    if enabled == (personalEntries ~= nil) then return end
    if enabled then
        save()
        personalEntries, entries = entries, {}
    else
        for index = #entries, 1, -1 do remove(index) end
        entries, personalEntries = personalEntries, nil
    end
    -- Ignore the clipboard already present at either side of the switch.
    observedChangeCount = hs.pasteboard.changeCount()
    clearedChangeCount = nil
    if not enabled then save() end
end

local function capture(text)
    if capturePaused then return end
    local changeCount = hs.pasteboard.changeCount()
    if changeCount == observedChangeCount then return end
    observedChangeCount = changeCount
    if changeCount == clearedChangeCount then return end
    local types = {}
    for _, item in ipairs(hs.pasteboard.allContentTypes() or {}) do
        for _, kind in ipairs(item) do
            if excludedTypes[kind] then return end
            types[kind] = true
        end
    end

    if type(text) ~= "string" and types["public.url"] then text = hs.pasteboard.readURL() end
    local entry, cleaned
    if types["public.png"] or types["public.tiff"] or types["public.jpeg"]
        or types["com.compuserve.gif"] or types["com.apple.icns"] then
        local image = hs.pasteboard.readImage()
        if not image then return end
        local size = image:size()
        if size.w * size.h > 16000000 then return end
        local path = personalEntries and os.tmpname() or state.imagePath()
        if not path then return end
        if not image:saveToFile(path, true, "PNG") then os.remove(path); return end
        local bytes = hs.fs.attributes(path, "size")
        if not bytes or bytes > maxImageBytes then os.remove(path); return end
        entry = {
            text = string.format("Image: %d × %d", math.floor(size.w), math.floor(size.h)),
            symbol = "photo", previewImage = path,
        }
    elseif type(text) == "string" and #text <= 65536 and text:find("%S") then
        local cleanedURL = cleanURL(text)
        if cleanedURL then
            cleaned = textEntry(cleanedURL)
            cleaned.symbol, cleaned.subtitle = "link", "Cleaned URL"
        end
        entry = textEntry(text)
    else
        return
    end

    entry.copiedAt = os.time()
    table.insert(entries, 1, entry)
    if cleaned then
        cleaned.copiedAt = entry.copiedAt
        table.insert(entries, 2, cleaned)
    end
    local images = 0
    for i = 1, #entries do
        if entries[i].previewImage then
            images = images + 1
            if images > maxImages then remove(i); break end
        end
    end
    while #entries > maxEntries do remove(#entries) end
    save()
end

function history.rows()
    local rows = {}
    for index, entry in ipairs(entries) do rows[index] = entry end
    return rows
end

function history.clear(minutes)
    local cutoff = minutes and os.time() - minutes * 60
    local removed = 0
    -- Ignore a clipboard change the watcher has not delivered yet.
    clearedChangeCount = hs.pasteboard.changeCount()
    for index = #entries, 1, -1 do
        if not cutoff or entries[index].copiedAt >= cutoff then
            remove(index)
            removed = removed + 1
        end
    end
    save()
    return removed
end

function history.copy(entry)
    if entry.previewText then
        return hs.pasteboard.setContents(entry.previewText)
    elseif entry.previewImage then
        local image = hs.image.imageFromPath(entry.previewImage)
        if image then return hs.pasteboard.writeObjects(image) end
    end
end

function history.paste(entry, target)
    if not history.copy(entry) or not target then return end
    local change = hs.pasteboard.changeCount()
    local pid = target:pid()
    if not target:activate() then return end
    local deadline = hs.timer.secondsSinceEpoch() + 0.6
    local timer
    timer = hs.timer.doEvery(0.04, function()
        if hs.pasteboard.changeCount() ~= change or hs.timer.secondsSinceEpoch() >= deadline then
            timer:stop()
            return
        end
        local front = hs.application.frontmostApplication()
        if front and front:pid() == pid then
            timer:stop()
            hs.eventtap.keyStroke({ "cmd" }, "v", 0, target)
        end
    end)
end

function history.pauseCapture()
    capturePaused = true
    return function()
        observedChangeCount = hs.pasteboard.changeCount()
        capturePaused = false
    end
end

if hs.settings.get("glassLauncherPublicRecordingMode") == true then history.setRecording(true) end
history.watcher = hs.pasteboard.watcher.new(function()
    capture(hs.pasteboard.getContents())
end)
capture(hs.pasteboard.getContents())

local previousShutdown = hs.shutdownCallback
hs.shutdownCallback = function()
    if personalEntries then
        for index = #entries, 1, -1 do remove(index) end
    else
        save()
    end
    if previousShutdown then previousShutdown() end
end

return history
